import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import type { MessageInstance } from 'antd/es/message/interface';
import type { ChatRequest } from '@ops/user-core';
import { authStore } from '@/adapters/auth/authStore';
import { browserStreamingTransport } from '@/adapters/streaming/browserStreamingTransport';
import { apiClient, chatApi } from '../../../api';
import {
  buildDailyWorkbenchSummaryPrompt,
  buildWeeklyWorkbenchSummaryPrompt,
  type SummaryExecutionItem,
} from '../lib/workbenchSummaryPrompt';
import {
  createInitialWorkbenchSummaryStateMap,
  formatSummaryTime,
  type WorkbenchSummaryState,
} from '../lib/workbenchSummaryState';
import { reduceWorkbenchSummaryStreamContent } from '../lib/workbenchSummaryStream';
import {
  saveWorkbenchSummary,
  type WorkbenchSummaryPeriod,
} from '../lib/workbenchSummaryStorage';

interface UseWorkbenchSummaryOptions {
  executionsReady: boolean;
  manualQueue: SummaryExecutionItem[];
  todayCompletedExecutions: SummaryExecutionItem[];
  todayFailedExecutionsCount: number;
  weekCompletedExecutions: SummaryExecutionItem[];
  message: MessageInstance;
}

export function useWorkbenchSummary({
  executionsReady,
  manualQueue,
  todayCompletedExecutions,
  todayFailedExecutionsCount,
  weekCompletedExecutions,
  message,
}: UseWorkbenchSummaryOptions) {
  const autoGeneratedSummaryRef = useRef<Record<WorkbenchSummaryPeriod, boolean>>({
    daily: false,
    weekly: false,
  });
  const [summaryState, setSummaryState] =
    useState<WorkbenchSummaryState>(createInitialWorkbenchSummaryStateMap);

  const dailySummaryPrompt = useMemo((): string => {
    return buildDailyWorkbenchSummaryPrompt({
      manualQueue,
      todayCompletedExecutions,
      todayFailedExecutionsCount,
    });
  }, [manualQueue, todayCompletedExecutions, todayFailedExecutionsCount]);

  const weeklySummaryPrompt = useMemo((): string => {
    return buildWeeklyWorkbenchSummaryPrompt({
      manualQueue,
      weekCompletedExecutions,
    });
  }, [manualQueue, weekCompletedExecutions]);

  const getAccessToken = useCallback(async (): Promise<string | null | undefined> => {
    return (await apiClient.ensureFreshAccessToken()) || authStore.getState().accessToken;
  }, []);

  const generateWorkbenchSummary = useCallback(
    async (
      period: WorkbenchSummaryPeriod,
      prompt: string,
      options?: { silent?: boolean }
    ): Promise<void> => {
      setSummaryState((current) => ({
        ...current,
        [period]: {
          ...current[period],
          status: 'running',
          error: undefined,
        },
      }));

      try {
        const token = await getAccessToken();
        if (!token) {
          throw new Error('当前登录态已失效，请重新登录后重试');
        }

        const request: ChatRequest = {
          // 每次生成用独立的新 sessionId，避免复用 'default' 会话历史。
          // 否则 LLM 会读到旧 task 模式留下的"已创建等待补充信息的执行单…"
          // 记录，并照着该模式幻觉出假的执行单 ID。
          sessionId: `workbench-summary-${period}-${Date.now()}`,
          message: prompt,
          config: {
            // 固定聊天模式：直接走 LLM 生成 markdown，不进 planner/技能匹配，
            // 避免被路由到 general_document_generator 并卡在 templateName。
            mode: 'chat',
            // 关闭 reasoning：后端会关闭推理、剥离 think 标签，且系统提示词要求
            // "直接输出结论，不要输出思考过程或  "-// 标签"。工作台总结只需干净 markdown。
            thinking: false,
          },
        };
        let finalContent = '';
        const streamHandle = chatApi.stream(
          browserStreamingTransport,
          token,
          request,
          (event) => {
            finalContent = reduceWorkbenchSummaryStreamContent(finalContent, event);
          }
        );

        await streamHandle.promise;

        const normalizedContent = finalContent.trim();
        if (!normalizedContent) {
          throw new Error('AI 没有返回可展示的总结内容');
        }

        const generatedAt = new Date().toISOString();
        saveWorkbenchSummary(period, normalizedContent, generatedAt);
        setSummaryState((current) => ({
          ...current,
          [period]: {
            status: 'completed',
            content: normalizedContent,
            generatedAt,
          },
        }));
        if (!options?.silent) {
          void message.success(period === 'daily' ? '今日总结已生成' : '本周总结已生成');
        }
      } catch (error) {
        const nextError = error instanceof Error ? error.message : 'AI 总结生成失败';
        setSummaryState((current) => ({
          ...current,
          [period]: {
            ...current[period],
            status: 'error',
            error: nextError,
          },
        }));
        if (!options?.silent) {
          void message.error(nextError);
        }
      }
    },
    [getAccessToken, message]
  );

  useEffect(() => {
    if (!executionsReady) {
      return;
    }

    const pendingPeriods: Array<{ period: WorkbenchSummaryPeriod; prompt: string }> = [
      { period: 'daily', prompt: dailySummaryPrompt },
      { period: 'weekly', prompt: weeklySummaryPrompt },
    ];

    pendingPeriods.forEach(({ period, prompt }) => {
      const currentSummary = summaryState[period];
      if (currentSummary.content) {
        autoGeneratedSummaryRef.current[period] = true;
        return;
      }
      if (currentSummary.status !== 'idle' || autoGeneratedSummaryRef.current[period]) {
        return;
      }
      autoGeneratedSummaryRef.current[period] = true;
      void generateWorkbenchSummary(period, prompt, { silent: true });
    });
  }, [
    dailySummaryPrompt,
    executionsReady,
    generateWorkbenchSummary,
    summaryState,
    weeklySummaryPrompt,
  ]);

  return {
    dailySummaryPrompt,
    formatSummaryTime,
    generateWorkbenchSummary,
    summaryState,
    weeklySummaryPrompt,
  };
}
